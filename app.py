import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import os
import gdown

# Configuração da página do aplicativo
st.set_page_config(page_title="Visualizador de Mapa de Dose 3D", layout="centered")

st.title("Mapa de Dose 3D")
st.write("Utilize o controle deslizante abaixo para navegar pelas fatias de profundidade (Eixo Z).")

# Nome do arquivo local no servidor e link de compartilhamento do Google Drive
ARQUIVO_DADOS = "3d-dose-map.dat"
LINK_DO_DRIVE = "https://drive.google.com/file/d/17_tO2ricRqTDGZNqwjcdfHfD_x0pIRqL/view?usp=sharing"

# Função em cache: baixa do Drive e processa a matriz 3D apenas na 1ª vez que o app abre
@st.cache_data(show_spinner="Baixando e processando o mapa de dose (70 MB)... Isso leva alguns segundos na primeira vez.")
def carregar_dados():
    if not os.path.exists(ARQUIVO_DADOS):
        gdown.download(url=LINK_DO_DRIVE, output=ARQUIVO_DADOS, quiet=False, fuzzy=True)

    colunas = ['X', 'Y', 'Z', 'Dose', 'Incerteza', 'IX', 'IY', 'IZ']

    df = pd.read_csv(
        ARQUIVO_DADOS,
        sep=r'\s+',
        comment='#',
        names=colunas,
        on_bad_lines='skip'
    )

    df = df.dropna().copy()

    df['IX'] = df['IX'].astype(int)
    df['IY'] = df['IY'].astype(int)
    df['IZ'] = df['IZ'].astype(int)

    nbx = int(df['IX'].max())
    nby = int(df['IY'].max())
    nbz = int(df['IZ'].max())

    dose_3d = np.zeros((nbx, nby, nbz), dtype=float)

    ix = df['IX'].values - 1
    iy = df['IY'].values - 1
    iz = df['IZ'].values - 1

    dose_3d[ix, iy, iz] = df['Dose'].values

    x_coords = np.sort(df['X'].unique())
    y_coords = np.sort(df['Y'].unique())
    z_coords = np.sort(df['Z'].unique())

    limites_xy = [
        float(x_coords.min()),
        float(x_coords.max()),
        float(y_coords.min()),
        float(y_coords.max())
    ]

    doses_validas = dose_3d[dose_3d > 1e-10]
    dose_maxima_referencia = np.percentile(doses_validas, 99.5)

    dose_normalizada = (dose_3d / dose_maxima_referencia) * 100.0

    # Liberar o dataframe da memória para deixar o servidor mais leve
    del df

    return dose_normalizada, limites_xy, z_coords, nbz

# Carrega os dados processados
dose_normalizada, limites_xy, z_coords, nbz = carregar_dados()

# Controle deslizante (substitui o antigo ipywidgets.IntSlider)
fatia_z = st.slider(
    "Fatia Z:",
    min_value=0,
    max_value=nbz - 1,
    value=nbz // 2,
    step=1
)

# Extrai os dados da fatia escolhida
corte_xy = dose_normalizada[:, :, fatia_z].T
profundidade_cm = z_coords[fatia_z]

# Cria e exibe o gráfico no Streamlit
fig, ax = plt.subplots(figsize=(9, 7))

im = ax.imshow(
    corte_xy,
    origin='lower',
    extent=limites_xy,
    cmap='gray_r',
    vmin=0,
    vmax=100,
    interpolation='nearest',
    aspect='equal'
)

fig.colorbar(im, ax=ax, label='Dose Relativa (%)')

ax.set_title(
    f'Mapa de Dose | Fatia Z = {fatia_z} '
    f'| Profundidade = {profundidade_cm:.3f} cm'
)
ax.set_xlabel('Eixo X (cm)')
ax.set_ylabel('Eixo Y (cm)')

fig.tight_layout()

# Mostra a figura na página web e limpa da memória em seguida
st.pyplot(fig)
plt.close(fig)